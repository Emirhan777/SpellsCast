import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const entry = new URL('../device-game/main.js', import.meta.url);
const result = await build({ entryPoints: [fileURLToPath(entry)], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'safari16.4', minify: true });
const template = await readFile(new URL('../device-game/index.html', import.meta.url), 'utf8');
const html = template.replace('/* GAME_SCRIPT */', () => result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script'));
const output = '// Generated by npm run build:device-game. Edit device-game/ or the shared game engine.\nexport const DEVICE_GAME_HTML = ' + JSON.stringify(html) + ';\n';
const target = new URL('../src/generated/device-game.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Device game bundle is stale. Run npm run build:device-game.');
} else await writeFile(target, output);
